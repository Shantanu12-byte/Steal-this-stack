import fs from 'fs/promises';
import path from 'path';

/**
 * Generates a ready-to-run starter project folder containing:
 *  - design-system.json (Full ground-truth extracted schema)
 *  - tailwind.config.js (Pre-mapped colors, fonts, shadows, border-radii)
 *  - index.html (Interactive styleguide & component kit using the stolen tokens)
 */
export async function generateStarterProject(designData, outputDir) {
  await fs.mkdir(outputDir, { recursive: true });

  // 1. Save full raw design-system.json
  await fs.writeFile(
    path.join(outputDir, 'design-system.json'),
    JSON.stringify(designData, null, 2),
    'utf-8'
  );

  // 2. Build semantic color map for Tailwind config
  const colorTokens = {};
  designData.colors.palette.forEach((hex, idx) => {
    colorTokens[`brand-${idx + 1}`] = hex;
  });

  const primaryFont = designData.typography.fontFamilies[0] || 'Inter';
  const secondaryFont = designData.typography.fontFamilies[1] || primaryFont;

  const tailwindConfigContent = `/** @type {import('tailwindcss').Config} */
// Auto-generated by steal-this-stack from ${designData.meta.url}
export default {
  content: ["./index.html", "./src/**/*.{js,ts,jsx,tsx}"],
  theme: {
    extend: {
      colors: {
        canvas: "${designData.colors.bodyBackground}",
        ink: "${designData.colors.bodyText}",
${Object.entries(colorTokens)
  .map(([k, v]) => `        "${k}": "${v}",`)
  .join('\n')}
      },
      fontFamily: {
        sans: ["${primaryFont}", "system-ui", "sans-serif"],
        display: ["${secondaryFont}", "system-ui", "sans-serif"],
      },
      borderRadius: {
${designData.tokens.borderRadii
  .slice(0, 4)
  .map((r, i) => `        "stolen-${i + 1}": "${r}",`)
  .join('\n')}
      },
      boxShadow: {
${designData.tokens.boxShadows
  .slice(0, 3)
  .map((s, i) => `        "stolen-${i + 1}": '${s}',`)
  .join('\n')}
      }
    },
  },
  plugins: [],
};
`;

  await fs.writeFile(path.join(outputDir, 'tailwind.config.js'), tailwindConfigContent, 'utf-8');

  // 3. Generate interactive index.html starter kit showcasing all stolen tokens
  const accentColor = designData.colors.palette[2] || designData.colors.palette[0] || '#6366F1';
  const firstShadow = designData.tokens.boxShadows[0] || '0 10px 30px -10px rgba(0,0,0,0.5)';
  const firstRadius = designData.tokens.borderRadii[0] || '12px';
  const firstTransition = designData.animations.transitions[0] || 'all 0.2s cubic-bezier(0.16, 1, 0.3, 1)';

  const colorSwatchesHtml = designData.colors.palette
    .map(
      (hex, i) => `
      <div class="group relative rounded-xl p-4 border border-white/10 bg-white/5 hover:scale-105 transition-transform cursor-pointer" onclick="navigator.clipboard.writeText('${hex}')">
        <div class="w-full h-16 rounded-lg mb-3 border border-white/15" style="background-color: ${hex};"></div>
        <div class="flex items-center justify-between text-xs font-mono">
          <span class="opacity-70">brand-${i + 1}</span>
          <span class="font-bold">${hex}</span>
        </div>
      </div>`
    )
    .join('\n');

  const svgGridHtml =
    designData.svgs.length > 0
      ? designData.svgs
          .map(
            (s) => `
        <div class="flex flex-col items-center justify-center p-4 rounded-xl border border-white/10 bg-white/5 hover:border-purple-500/50 transition">
          <div class="w-8 h-8 flex items-center justify-center text-current mb-2 overflow-hidden">
            ${s.html}
          </div>
          <span class="text-[11px] font-mono opacity-60">${s.id}</span>
        </div>`
          )
          .join('\n')
      : '<p class="text-sm opacity-60">No inline vector SVGs found on target viewport.</p>';

  const googleFontLink = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(primaryFont)}:wght@400;500;600;700&display=swap`;

  const indexHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Stolen Stack Starter — ${designData.meta.title || designData.meta.url}</title>
  <script src="https://cdn.tailwindcss.com"></script>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link href="${googleFontLink}" rel="stylesheet">
  <style>
    :root {
      --bg-canvas: ${designData.colors.bodyBackground};
      --text-ink: ${designData.colors.bodyText};
      --accent: ${accentColor};
      --radius-primary: ${firstRadius};
      --shadow-primary: ${firstShadow};
      --transition-primary: ${firstTransition};
    }
    body {
      background-color: var(--bg-canvas);
      color: var(--text-ink);
      font-family: '${primaryFont}', system-ui, -apple-system, sans-serif;
    }
    .stolen-card {
      border-radius: var(--radius-primary);
      box-shadow: var(--shadow-primary);
      transition: var(--transition-primary);
    }
  </style>
</head>
<body class="min-h-screen antialiased selection:bg-purple-500 selection:text-white">
  <div class="max-w-6xl mx-auto px-6 py-16">
    <!-- Header Badge -->
    <div class="inline-flex items-center gap-2 px-3 py-1.5 rounded-full border border-white/15 bg-white/5 text-xs font-mono mb-6">
      <span class="w-2 h-2 rounded-full bg-emerald-400 animate-pulse"></span>
      Reverse-Engineered from <a href="${designData.meta.url}" target="_blank" class="underline font-semibold">${designData.meta.url}</a>
    </div>

    <!-- Hero Section using Stolen Typography & Colors -->
    <div class="stolen-card p-10 border border-white/10 bg-white/[0.03] backdrop-blur-xl mb-14">
      <h1 class="text-4xl md:text-6xl font-bold tracking-tight mb-4">
        ${designData.meta.title || 'Stolen Design System'}
      </h1>
      <p class="text-lg opacity-75 max-w-2xl mb-8">
        This starter kit uses the exact computed CSS variables, font families (<strong>${primaryFont}</strong>), border radii (<code>${firstRadius}</code>), and transition physics extracted directly from the live DOM.
      </p>
      <div class="flex flex-wrap gap-4">
        <button class="px-6 py-3 font-medium text-white stolen-card hover:opacity-90" style="background-color: ${accentColor};">
          Primary Action Button
        </button>
        <a href="./design-system.json" target="_blank" class="px-6 py-3 font-mono text-sm border border-white/20 rounded-lg hover:bg-white/5 transition">
          Inspect design-system.json →
        </a>
      </div>
    </div>

    <!-- Extracted Color Palette -->
    <section class="mb-14">
      <h2 class="text-xl font-bold mb-2">1. Computed Color Palette (Click to Copy Hex)</h2>
      <p class="text-sm opacity-60 mb-6">Sampled from live rendered DOM nodes via <code>window.getComputedStyle()</code></p>
      <div class="grid grid-cols-2 sm:grid-cols-4 md:grid-cols-6 gap-4">
        ${colorSwatchesHtml}
      </div>
    </section>

    <!-- Typography & Physics -->
    <section class="grid md:grid-cols-2 gap-6 mb-14">
      <div class="stolen-card p-6 border border-white/10 bg-white/[0.02]">
        <h3 class="text-lg font-bold mb-4">2. Typography Hierarchy</h3>
        <div class="space-y-3 font-mono text-xs">
          <div><span class="opacity-50">Detected Fonts:</span> <strong>${designData.typography.fontFamilies.join(', ') || 'System UI'}</strong></div>
          <div><span class="opacity-50">H1 Size / Weight:</span> <code>${designData.typography.scale.h1?.fontSize || '48px'} / ${designData.typography.scale.h1?.fontWeight || '700'}</code></div>
          <div><span class="opacity-50">Body Size / Line:</span> <code>${designData.typography.scale.p?.fontSize || '16px'} / ${designData.typography.scale.p?.lineHeight || '1.5'}</code></div>
        </div>
      </div>

      <div class="stolen-card p-6 border border-white/10 bg-white/[0.02]">
        <h3 class="text-lg font-bold mb-4">3. Radii, Shadows & Motion Curves</h3>
        <div class="space-y-3 font-mono text-xs overflow-hidden">
          <div><span class="opacity-50">Border Radii:</span> <code>${designData.tokens.borderRadii.join(', ') || '8px'}</code></div>
          <div class="truncate"><span class="opacity-50">Transition Curve:</span> <code>${firstTransition}</code></div>
          <div class="truncate"><span class="opacity-50">Backdrop Blur:</span> <code>${designData.tokens.backdropFilters[0] || 'blur(12px)'}</code></div>
        </div>
      </div>
    </section>

    <!-- Extracted SVGs -->
    <section>
      <h2 class="text-xl font-bold mb-2">4. Extracted Inline Vector Assets (SVGs)</h2>
      <p class="text-sm opacity-60 mb-6">Captured directly from the live page DOM</p>
      <div class="grid grid-cols-3 sm:grid-cols-6 gap-4">
        ${svgGridHtml}
      </div>
    </section>
  </div>
</body>
</html>`;

  await fs.writeFile(path.join(outputDir, 'index.html'), indexHtml, 'utf-8');
}
